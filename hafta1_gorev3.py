# İlk 6 terim ile yaklaşık π hesabı:
# π ≈ 4 * (1 - 1/3 + 1/5 - 1/7 + 1/9 - 1/11)
print(4 * (1 - 1 / 3 + 1 / 5 - 1 / 7 + 1 / 9 - 1 / 11))

# İlk 7 terim ile yaklaşık π hesabı:
# π ≈ 4 * (1 - 1/3 + 1/5 - 1/7 + 1/9 - 1/11 + 1/13)
print(4 * (1 - 1 / 3 + 1 / 5 - 1 / 7 + 1 / 9 - 1 / 11 + 1 / 13))
